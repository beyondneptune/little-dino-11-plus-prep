#!/usr/bin/env python3
"""
Coverage report + integrity checks for the Dino Ages taxonomy.

Reads content/topics.yaml + content/ages.yaml + content/creatures.yaml and
checks placement integrity, then writes content/coverage_report.md (ages x
subject grid, subject mix, per-creature topics, readiness, ET, fact-check
status). validate() is what tests/test_taxonomy.py asserts is empty.
"""
import sys
from collections import Counter, defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CONTENT = ROOT / "content"
SUBJECTS = ["Maths", "English", "VR", "NVR"]
PROPORTION = {"Maths": 38, "English": 35, "VR": 13, "NVR": 14}


def load():
    topics = yaml.safe_load((CONTENT / "topics.yaml").read_text())["topics"]
    ages = yaml.safe_load((CONTENT / "ages.yaml").read_text())["ages"]
    return topics, ages


def load_creatures():
    return yaml.safe_load((CONTENT / "creatures.yaml").read_text())["creatures"]


def validate(topics, ages):
    """Integrity problems that must never ship. Empty list == healthy."""
    issues = []
    age_ids = {a["id"] for a in ages}
    by_id = {}
    for t in topics:
        if t["id"] in by_id:
            issues.append(f"duplicate topic id {t['id']}")
        by_id[t["id"]] = t
    for t in topics:
        if t["age"] not in age_ids:
            issues.append(f"{t['id']} is on unknown age {t['age']}")
        for p in t.get("prerequisites", []):
            if p not in by_id:
                issues.append(f"{t['id']} needs unknown prerequisite {p}")
            elif by_id[p]["age"] > t["age"]:
                issues.append(f"{t['id']} (age {t['age']}) depends on {p} "
                              f"on later age {by_id[p]['age']}")
    return issues


def report(topics, ages, creatures):
    issues = validate(topics, ages)
    subj = [t for t in topics if t["subject"] in SUBJECTS]
    et = [t for t in topics if t["subject"] == "ET"]
    grid = defaultdict(Counter)
    ready = defaultdict(Counter)
    for t in subj:
        grid[t["age"]][t["subject"]] += 1
    for t in topics:
        ready[t["age"]][t["content_readiness"]] += 1
    name_of = {a["id"]: a["name"] for a in ages}

    L = ["# Dino Ages — coverage report", "",
         "Generated by scripts/coverage_report.py from the built taxonomy "
         "(scripts/build_taxonomy.py). All 351 master topics placed "
         "(340 subject + 11 exam-technique).", "",
         "## Topics per age × subject", "",
         "| Age | " + " | ".join(SUBJECTS) + " | subj total | ET |",
         "|---|" + "|".join(["---"] * len(SUBJECTS)) + "|---|---|"]
    for a in ages:
        row = grid[a["id"]]
        et_n = sum(1 for t in et if t["age"] == a["id"])
        L.append(f"| {a['id']}. {a['name']} | "
                 + " | ".join(str(row.get(s, 0)) for s in SUBJECTS)
                 + f" | {sum(row.values())} | {et_n} |")
    tot = Counter(t["subject"] for t in subj)
    L.append("| **Total** | "
             + " | ".join(f"**{tot.get(s, 0)}**" for s in SUBJECTS)
             + f" | **{len(subj)}** | **{len(et)}** |")

    L += ["", "## Subject mix per age (share %, target 38/35/13/14, +-2pp)", "",
          "| Age | Maths | English | VR | NVR |", "|---|---|---|---|---|"]
    for a in ages:
        row = grid[a["id"]]
        t = sum(row.values())
        L.append(f"| {a['id']} | "
                 + " | ".join(f"{100*row.get(s,0)/t:.1f}%" for s in SUBJECTS) + " |")

    L += ["", "## Content readiness per age (V machine / R authored+review / P parent)",
          "", "| Age | V | R | P |", "|---|---|---|---|"]
    for a in ages:
        r = ready[a["id"]]
        L.append(f"| {a['id']} | {r.get('V',0)} | {r.get('R',0)} | {r.get('P',0)} |")
    gr = Counter(t["content_readiness"] for t in topics)
    L.append(f"| **Total** | **{gr.get('V',0)}** | **{gr.get('R',0)}** | **{gr.get('P',0)}** |")

    L += ["", "## Creatures and their topics", ""]
    cre_by_age = defaultdict(list)
    for c in creatures:
        cre_by_age[c["age"]].append(c)
    for a in ages:
        et_ids = ", ".join(t["id"] for t in et if t["age"] == a["id"]) or "—"
        L.append(f"### Age {a['id']}: {a['name']}  ·  {a['period']}  ·  band {a['band']}")
        for c in cre_by_age[a["id"]]:
            dino = " 🦖" if c["is_dinosaur"] else ""
            L.append(f"- **{c['name']}**{dino} ({c['subject']}, {len(c['topics'])} topics): "
                     + ", ".join(c["topics"]))
        L.append(f"- *Fossil Dig* (mixed timed test + ~25% review) · ET: {et_ids}")
        L.append("")

    verified = sum(1 for c in creatures if c["fact_card"]["verified"])
    sourced = sum(1 for c in creatures
                  if c["fact_card"]["source_1"] and c["fact_card"]["source_2"])
    L += ["## Fact-check status",
          f"- Creatures: {len(creatures)} · with two sources: {sourced} · "
          f"parent-approved (verified): {verified}",
          "",
          "## Integrity checks",
          f"- Topics: {len(topics)} (subject {len(subj)} + ET {len(et)}) · "
          f"Ages: {len(ages)} · Creatures: {len(creatures)}",
          "- Placement integrity (ids unique, valid age, prereqs not later): "
          + ("✅ PASS" if not issues else "❌ FAIL")]
    if issues:
        L += ["", "### Problems"] + [f"- {i}" for i in issues]
    out = "\n".join(L) + "\n"
    (CONTENT / "coverage_report.md").write_text(out)
    return out, issues


if __name__ == "__main__":
    topics, ages = load()
    creatures = load_creatures()
    out, issues = report(topics, ages, creatures)
    print(f"Wrote content/coverage_report.md · issues: {len(issues)}")
    sys.exit(1 if issues else 0)
